#!/usr/bin/env bash
# Writes THIRD_PARTY_NOTICES.md: the licences of everything compiled into the zerochat and zsf
# binaries. The release workflow ships it in every archive and npm package.
#
#   scripts/third-party-notices.sh [output]   (or `make notices`; default target/THIRD_PARTY_NOTICES.md)
#   scripts/third-party-notices.sh --tool-version   # the cargo-about version it needs
#
# 1. Rust: cargo-about over the workspace (about.toml: accepted licences, release targets, no dev or
#    build dependencies; about.hbs: the layout). A crate under a licence not in about.toml fails.
# 2. Web UI: the production npm dependencies bundled into web/dist, which the server embeds
#    (npm/web-licenses.js; needs web/node_modules: npm --prefix web ci).
#
# Needs cargo-about $CARGO_ABOUT_VERSION:
#   cargo install --locked cargo-about --version <version> --features cli
# CARGO_ABOUT overrides the command (default `cargo about`); WEB_DIR the web project (default web).
set -euo pipefail
cd "$(dirname "$0")/.."

CARGO_ABOUT_VERSION=0.9.3
if [ "${1:-}" = --tool-version ]; then
  echo "$CARGO_ABOUT_VERSION"
  exit 0
fi

out="${1:-target/THIRD_PARTY_NOTICES.md}"
read -r -a about <<<"${CARGO_ABOUT:-cargo about}"
web="${WEB_DIR:-web}"

have=$("${about[@]}" --version 2>/dev/null | awk '{print $2}') || true
if [ "$have" != "$CARGO_ABOUT_VERSION" ]; then
  echo "third-party-notices: needs cargo-about $CARGO_ABOUT_VERSION (found: ${have:-none})" >&2
  echo "  cargo install --locked cargo-about --version $CARGO_ABOUT_VERSION --features cli" >&2
  exit 1
fi
if [ ! -d "$web/node_modules" ]; then
  echo "third-party-notices: $web/node_modules is missing (npm --prefix $web ci)" >&2
  exit 1
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
"${about[@]}" generate --workspace --fail about.hbs -o "$tmp/rust.md"
node npm/web-licenses.js "$web" >"$tmp/web.md"

mkdir -p "$(dirname "$out")"
{
  echo "# Third-party notices"
  echo
  echo "The zerochat and zsf binaries contain the third-party code listed here; zerochat also embeds the"
  echo "web UI. Generated by scripts/third-party-notices.sh for zerochat $(node npm/build.js version)."
  echo
  cat "$tmp/rust.md"
  echo
  cat "$tmp/web.md"
} >"$out"
echo "wrote $out ($(grep -c '^- \[' "$out") packages)"
